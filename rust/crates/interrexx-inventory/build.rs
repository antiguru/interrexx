//! Derives Rust tables from the checked-in interface tables in `data/` and
//! the message texts in `messages/`. Nothing outside this crate is read.

use interrexx_upstream::{builtins, errors, messages};
use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-changed=data/errors.tsv");
    println!("cargo::rerun-if-changed=data/builtins.txt");
    // A new `messages/<major>.tsv` changes the directory, an edit changes a
    // file.
    println!("cargo::rerun-if-changed=messages");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let table = errors::Table::from_tsv(&read("data/errors.tsv"));
    let texts = load_messages(&table);
    std::fs::write(out.join("errors.rs"), generate_errors(&table, &texts))
        .expect("writing errors.rs");
    let names = builtins::from_text(&read("data/builtins.txt"));
    std::fs::write(out.join("builtins.rs"), generate_builtins(&names))
        .expect("writing builtins.rs");
}

/// The texts under `messages/`, keyed by code, after checking that they fit
/// the table and that every row of the table has one.
fn load_messages(table: &errors::Table) -> HashMap<(u16, u16), String> {
    let dir = std::path::Path::new("messages");
    let texts = messages::load_dir(dir)
        .unwrap_or_else(|problems| panic!("messages/ is not sound:\n{}", problems.join("\n")));
    for text in &texts {
        println!("cargo::rerun-if-changed=messages/{}.tsv", text.major);
    }
    let mut problems = messages::validate(table, &texts);
    problems.extend(messages::missing(table, &texts));
    assert!(
        problems.is_empty(),
        "messages/ does not fit data/errors.tsv:\n{}",
        problems.join("\n")
    );
    texts
        .into_iter()
        .map(|t| ((t.major, t.sub), t.text))
        .collect()
}

fn read(path: &str) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {path}: {e}"))
}

// ---------------------------------------------------------------- messages --

/// The Rust tables for `table`'s messages, each with its text from `texts`.
fn generate_errors(table: &errors::Table, texts: &HashMap<(u16, u16), String>) -> String {
    let mut out = String::from(
        "// Generated by build.rs from data/errors.tsv and messages/. Do not edit.\n\
         pub struct Message {\n\
         \x20   pub major: u16,\n\
         \x20   pub sub: u16,\n\
         \x20   pub number: u16,\n\
         \x20   pub symbol: &'static str,\n\
         \x20   pub text: &'static str,\n\
         }\n\n\
         pub fn lookup(major: u16, sub: u16) -> Option<&'static Message> {\n\
         \x20   MESSAGES.iter().find(|m| m.major == major && m.sub == sub)\n\
         }\n\n\
         pub static MESSAGES: &[Message] = &[\n",
    );
    for r in &table.rows {
        writeln!(
            out,
            "    Message {{ major: {}, sub: {}, number: {}, symbol: {:?}, text: {:?} }},",
            r.major,
            r.sub,
            r.number,
            r.symbol,
            texts[&(r.major, r.sub)]
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// One message, typed by how many inserts it takes: `N` is the row's\n\
         /// `inserts` column in `data/errors.tsv`. Its text may show fewer.\n\
         #[derive(Copy, Clone, PartialEq, Eq, Debug)]\n\
         pub struct Msg<const N: usize> {\n\
         \x20   major: u16,\n\
         \x20   sub: u16,\n\
         }\n\n\
         impl<const N: usize> Msg<N> {\n\
         \x20   /// The (major, sub) pair this message is catalogued under.\n\
         \x20   pub const fn code(self) -> (u16, u16) {\n\
         \x20       (self.major, self.sub)\n\
         \x20   }\n\n\
         \x20   /// How many inserts the message takes.\n\
         \x20   pub const fn arity(self) -> usize {\n\
         \x20       N\n\
         \x20   }\n\
         }\n\n",
    );
    for r in &table.rows {
        writeln!(
            out,
            "pub const E{major}_{sub}: Msg<{n}> = Msg {{ major: {major}, sub: {sub} }};",
            major = r.major,
            sub = r.sub,
            n = r.inserts,
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str(
        "\n/// Every message constant's (major, sub) pair and arity.\n\
         pub const ARITIES: &[((u16, u16), usize)] = &[\n",
    );
    for r in &table.rows {
        writeln!(
            out,
            "    (E{major}_{sub}.code(), E{major}_{sub}.arity()),",
            major = r.major,
            sub = r.sub,
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("];\n");
    out
}

// ---------------------------------------------------------------- builtins --

fn generate_builtins(names: &[String]) -> String {
    let mut out = String::from(
        "// Generated by build.rs from data/builtins.txt.\n\
         // Do not edit. Order is table order, which is the index the parser\n\
         // resolves builtins through -- do not sort it.\n\
         pub static NAMES: &[&str] = &[\n",
    );
    for n in names {
        writeln!(out, "    {n:?},").expect("writing to a String cannot fail");
    }
    out.push_str("];\n");
    out
}
