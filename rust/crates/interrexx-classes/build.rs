//! Emits the primitive-class creation list and each class block's own
//! method-name table from `data/classes.tsv`, the checked-in table that
//! `interrexx-upstream` derives from the pinned ooRexx sources. The build
//! reads nothing outside this crate, and nothing generated is written into
//! `src/`.

use interrexx_upstream::classes::Table;
use std::path::{Path, PathBuf};

const TABLE: &str = "data/classes.tsv";

fn main() {
    println!("cargo::rerun-if-changed={TABLE}");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let src = std::fs::read_to_string(Path::new(TABLE))
        .unwrap_or_else(|e| panic!("cannot read {TABLE}: {e}"));

    std::fs::write(
        out.join("setup_classes.rs"),
        generate(&Table::from_tsv(&src)),
    )
    .expect("writing setup_classes.rs");
}

fn generate(table: &Table) -> String {
    let mut out = String::from(
        "// Generated by build.rs from data/classes.tsv. Do not edit.\n\n\
         /// One bootstrap macro invocation, in file order.\n\
         #[derive(Clone, Copy)]\n\
         pub enum Op {\n\
         \x20   AddClassMethod(&'static str),\n\
         \x20   AddInstanceMethod(&'static str),\n\
         \x20   /// `AddPrivateMethod`, whose method the ordinary private\n\
         \x20   /// check refuses from a program context.\n\
         \x20   AddPrivateInstanceMethod(&'static str),\n\
         \x20   /// `AddProtectedMethod`, whose method the security manager\n\
         \x20   /// is asked about.\n\
         \x20   AddProtectedInstanceMethod(&'static str),\n\
         \x20   /// `AddClassProtectedMethod`.\n\
         \x20   AddProtectedClassMethod(&'static str),\n\
         \x20   InheritInstanceMethods(&'static str),\n\
         \x20   RemoveInstanceMethod(&'static str),\n\
         \x20   HideInstanceMethod(&'static str),\n\
         }\n\n\
         pub struct ClassDefinition {\n\
         \x20   pub name: &'static str,\n\
         \x20   pub ops: &'static [Op],\n\
         \x20   /// Closed by `EndSpecialClassDefinition` rather than\n\
         \x20   /// `EndClassDefinition`, so the class object goes to\n\
         \x20   /// `addToSystem`'s kernel directory and never to\n\
         \x20   /// `completeSystemClass`'s `.environment`.\n\
         \x20   pub system_only: bool,\n\
         }\n\n\
         /// Every class the interpreter creates at bootstrap, in creation\n\
         /// order, by its class block's name.\n\
         pub static SETUP_CLASSES: &[&str] = &[\n",
    );
    for name in &table.creation {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n\npub static CLASS_DEFINITIONS: &[ClassDefinition] = &[\n");
    for def in &table.blocks {
        out.push_str("    ClassDefinition { name: ");
        out.push_str(&format!("{:?}", def.name));
        out.push_str(", ops: &[\n");
        for op in &def.ops {
            // The table's kind spellings are the enum's variant names.
            let variant = op.kind.name();
            out.push_str(&format!("        Op::{variant}({:?}),\n", op.name));
        }
        out.push_str(&format!("    ], system_only: {} }},\n", def.system_only));
    }
    out.push_str("];\n");
    out
}
