//! Derives the interface tables that interrexx checks in from the pinned
//! ooRexx source tree, and compares a checked-in table with a fresh
//! derivation.
//!
//! The build never reads the source tree for these tables: it reads the
//! tables. Only the `interrexx-upstream` binary (`write` and `check`) reads
//! the tree, through `$REXX_UPSTREAM`. The message texts are the exception
//! until they are replaced: `interrexx-inventory`'s build script still
//! reads them through the same variable.

pub mod builtins;
pub mod classes;
pub mod errors;

/// The first line of every generated table. `sha` is the pinned source
/// tree's revision, so a revision bump without regeneration fails `check`.
pub fn header(sha: &str) -> String {
    format!("# generated by interrexx-upstream from ooRexx {sha}; do not edit\n")
}

/// Describes how `have` (the checked-in text) differs from `want` (a fresh
/// derivation), or `None` when they are identical. Lines only in the
/// checked-in text are listed with `-`, lines only in the fresh derivation
/// with `+`, each with its line number in its own text.
pub fn difference(have: &str, want: &str) -> Option<String> {
    if have == want {
        return None;
    }
    let a: Vec<&str> = have.lines().collect();
    let b: Vec<&str> = want.lines().collect();
    // Longest common subsequence, so a row that also occurs elsewhere in
    // the table is still reported where it changed.
    let mut common = vec![vec![0usize; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            common[i][j] = if a[i] == b[j] {
                common[i + 1][j + 1] + 1
            } else {
                common[i + 1][j].max(common[i][j + 1])
            };
        }
    }
    let mut report = String::new();
    let (mut i, mut j) = (0, 0);
    while i < a.len() || j < b.len() {
        if i < a.len() && j < b.len() && a[i] == b[j] {
            i += 1;
            j += 1;
        } else if j == b.len() || (i < a.len() && common[i + 1][j] >= common[i][j + 1]) {
            report.push_str(&format!("- {}: {}\n", i + 1, a[i]));
            i += 1;
        } else {
            report.push_str(&format!("+ {}: {}\n", j + 1, b[j]));
            j += 1;
        }
    }
    if report.is_empty() {
        // Same lines, but the texts differ: only a trailing newline.
        report.push_str("the texts differ only in their final newline\n");
    }
    Some(report)
}
