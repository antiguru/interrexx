use super::*;
use crate::difference;

/// An invented catalogue in the source's shape: a major with nested
/// submessages, `<Sub position>` inserts, entities and quote markup. The
/// texts are made up.
const SYNTHETIC: &str = r#"<?xml version="1.0"?>
<Messages>
  <Message>
    <Code>91</Code>
    <MessageNumber>100</MessageNumber>
    <SymbolicName>Error_Invented</SymbolicName>
    <Text>Invented &amp; <q>quoted</q> failure.</Text>
    <Subcodes>
      <SubMessage>
        <Code>91</Code>
        <Subcode>1</Subcode>
        <MessageNumber>101</MessageNumber>
        <SymbolicName>Error_Invented_one</SymbolicName>
        <Text>Item <Sub position="1"/> of <Sub position="3"/> is <sq/>odd<dq/> &lt;here&gt;.</Text>
      </SubMessage>
      <SubMessage>
        <Code>91</Code>
        <Subcode>2</Subcode>
        <MessageNumber>102</MessageNumber>
        <SymbolicName>Error_Invented_two</SymbolicName>
        <Text>Two <Sub position="2"/> and <Sub position="2"/>.</Text>
      </SubMessage>
    </Subcodes>
  </Message>
  <Message>
    <Code>27</Code>
    <MessageNumber>200</MessageNumber>
    <SymbolicName>Error_Overridden</SymbolicName>
    <Subcodes>
      <SubMessage>
        <Code>27</Code>
        <Subcode>1</Subcode>
        <MessageNumber>201</MessageNumber>
        <SymbolicName>Error_Overridden_one</SymbolicName>
        <Text>No inserts shown.</Text>
      </SubMessage>
    </Subcodes>
    <Text>Overridden.</Text>
  </Message>
</Messages>
"#;

fn row(table: &Table, major: u16, sub: u16) -> &Row {
    table
        .rows
        .iter()
        .find(|r| (r.major, r.sub) == (major, sub))
        .expect("the row exists")
}

#[test]
fn errors_parse_synthetic() {
    let messages = parse_messages(SYNTHETIC);
    let texts: Vec<_> = messages.iter().map(|m| m.text.as_str()).collect();
    assert_eq!(
        texts,
        [
            "Item &1 of &3 is 'odd\" <here>.",
            "Two &2 and &2.",
            "Invented & \"quoted\" failure.",
            "No inserts shown.",
            "Overridden.",
        ]
    );
    let table = Table::from_messages(&messages);
    // Nested submessages keep their own code and do not overwrite the major's.
    assert_eq!(row(&table, 91, 1).number, 101);
    assert_eq!(row(&table, 91, 1).symbol, "Error_Invented_one");
    assert_eq!(row(&table, 91, 0).number, 100);
    // The insert count is the highest position, whether or not the lower ones show.
    assert_eq!(row(&table, 91, 1).inserts, 3);
    assert_eq!(row(&table, 91, 1).rendered, [1, 3]);
    assert_eq!(row(&table, 91, 2).inserts, 2);
    assert_eq!(row(&table, 91, 2).rendered, [2]);
    assert_eq!(row(&table, 91, 0).inserts, 0);
    assert!(row(&table, 91, 0).rendered.is_empty());
    // An override raises the count past what the text shows.
    assert_eq!(row(&table, 27, 1).inserts, 1);
    assert!(row(&table, 27, 1).rendered.is_empty());
}

#[test]
fn errors_table_survives_its_text() {
    let table = Table::parse(SYNTHETIC);
    let text = table.to_tsv("0123abc");
    assert!(
        text.starts_with("# generated by interrexx-upstream from ooRexx 0123abc; do not edit\n")
    );
    assert!(text.contains("91\t1\t101\tError_Invented_one\t3\t1,3\n"));
    assert!(text.contains("27\t1\t201\tError_Overridden_one\t1\t-\n"));
    assert_eq!(Table::from_tsv(&text), table);
    // No text column: an invented text never reaches the table.
    assert!(!text.contains("Invented &"));
}

#[test]
fn errors_check_reports_a_changed_insert_count() {
    let text = Table::parse(SYNTHETIC).to_tsv("0123abc");
    assert_eq!(difference(&text, &text), None);
    let edited = text.replace(
        "91\t1\t101\tError_Invented_one\t3\t1,3",
        "91\t1\t101\tError_Invented_one\t2\t1,3",
    );
    assert_ne!(edited, text);
    let report = difference(&edited, &text).expect("a changed row is reported");
    assert!(
        report.contains("- 5: 91\t1\t101\tError_Invented_one\t2\t1,3"),
        "{report}"
    );
    assert!(
        report.contains("+ 5: 91\t1\t101\tError_Invented_one\t3\t1,3"),
        "{report}"
    );
}

#[test]
fn errors_check_reports_a_changed_rendered_set() {
    let text = Table::parse(SYNTHETIC).to_tsv("0123abc");
    let edited = text.replace(
        "91\t1\t101\tError_Invented_one\t3\t1,3",
        "91\t1\t101\tError_Invented_one\t3\t1,2,3",
    );
    assert_ne!(edited, text);
    let report = difference(&edited, &text).expect("a changed set is reported");
    assert!(
        report.contains("1,2,3") && report.contains("+ 5:"),
        "{report}"
    );
}

