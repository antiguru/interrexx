use super::*;
use crate::difference;

/// An invented table in the source's shape, long enough for the sanity floor.
fn synthetic() -> String {
    let mut src = String::from("int x;\npbuiltin LanguageParser::builtinTable[] =\n{\n    NULL,\n");
    for i in 0..60 {
        src.push_str(&format!("    &builtin_function_FN{i:02},\n"));
    }
    src.push_str("};\nint y;\n&builtin_function_AFTER,\n");
    src
}

#[test]
fn builtins_parse_synthetic() {
    let names = parse(&synthetic());
    assert_eq!(names.len(), 60);
    assert_eq!(names[0], "FN00");
    assert_eq!(names[59], "FN59");
}

#[test]
fn builtins_text_keeps_table_order() {
    let mut names = parse(&synthetic());
    // A table that is not alphabetical must round trip unsorted.
    names.swap(0, 7);
    let text = to_text(&names, "0123abc");
    assert!(
        text.starts_with("# generated by interrexx-upstream from ooRexx 0123abc; do not edit\n")
    );
    assert_eq!(from_text(&text), names);
}

#[test]
fn builtins_check_reports_an_order_swap() {
    let names = parse(&synthetic());
    let text = to_text(&names, "0123abc");
    let mut swapped = names.clone();
    swapped.swap(0, 1);
    let report = difference(&to_text(&swapped, "0123abc"), &text).expect("a swap is reported");
    assert!(
        report.contains("- 3: FN01") && report.contains("+ 4: FN01"),
        "{report}"
    );
}

