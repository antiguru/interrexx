use super::*;
use crate::difference;

/// An invented bootstrap text in the source's shape: a creation checklist,
/// three blocks, one inheriting from another, one closed the special way.
const SYNTHETIC: &str = r#"
    void createImage()
    {
        RexxClass::createInstance();
        RexxObject::createInstance();
        RexxInfo::createInstance();
    }
#define AddMethod(name, entry, arity) ignored
    StartClassDefinition(Object)
    AddMethod("HELLO", Fn::hello, 0);
    AddUnguardedMethod("\\=", Fn::differs, 1);
    AddClassMethod("make", Fn::make, A_COUNT);
    AddClassProtectedMethod("seal", Fn::seal, 2);
    AddPrivateMethod("hidden", Fn::hidden, 0);
    AddProtectedMethod("guarded", Fn::guarded, 0);
    EndClassDefinition(Object)
    StartClassDefinition(Class)
    InheritInstanceMethods(Object)
    RemoveMethod("HELLO");
    HideMethod("guarded");
    EndClassDefinition(Class)
    StartClassDefinition(RexxInfo)
    EndSpecialClassDefinition(RexxInfo)
"#;

/// The synthetic text has too few blocks for `Table::parse`'s sanity floor,
/// so the tests go through the checklist and block parsers it is built from.
fn synthetic_table() -> Table {
    let blocks = parse_blocks(SYNTHETIC);
    let creation = parse_checklist(SYNTHETIC)
        .iter()
        .map(|name| {
            CHECKLIST_TO_BLOCK
                .iter()
                .find(|(known, _)| known == name)
                .expect("mapped")
                .1
                .to_string()
        })
        .collect();
    Table { creation, blocks }
}

fn ops(block: &Block) -> Vec<(Kind, &str, Option<Arity>)> {
    block
        .ops
        .iter()
        .map(|op| (op.kind, op.name.as_str(), op.arity))
        .collect()
}

#[test]
fn classes_parse_synthetic() {
    let table = synthetic_table();
    assert_eq!(table.creation, ["Class", "Object", "RexxInfo"]);
    let names: Vec<_> = table.blocks.iter().map(|b| b.name.as_str()).collect();
    assert_eq!(names, ["Object", "Class", "RexxInfo"]);
    assert!(!table.blocks[0].system_only);
    assert!(table.blocks[2].system_only);
    assert_eq!(
        ops(&table.blocks[0]),
        [
            (Kind::AddInstanceMethod, "HELLO", Some(Arity::Max(0))),
            (Kind::AddInstanceMethod, "\\=", Some(Arity::Max(1))),
            (Kind::AddClassMethod, "make", Some(Arity::Any)),
            (Kind::AddProtectedClassMethod, "seal", Some(Arity::Max(2))),
            (
                Kind::AddPrivateInstanceMethod,
                "hidden",
                Some(Arity::Max(0))
            ),
            (
                Kind::AddProtectedInstanceMethod,
                "guarded",
                Some(Arity::Max(0))
            ),
        ]
    );
    assert_eq!(
        ops(&table.blocks[1]),
        [
            (Kind::InheritInstanceMethods, "Object", None),
            (Kind::RemoveInstanceMethod, "HELLO", None),
            (Kind::HideInstanceMethod, "guarded", None),
        ]
    );
}

#[test]
fn classes_table_survives_its_text() {
    let table = synthetic_table();
    let text = table.to_tsv("0123abc");
    assert!(
        text.starts_with("# generated by interrexx-upstream from ooRexx 0123abc; do not edit\n")
    );
    assert_eq!(Table::from_tsv(&text), table);
}

#[test]
fn classes_check_reports_a_changed_row() {
    let text = synthetic_table().to_tsv("0123abc");
    assert_eq!(difference(&text, &text), None);
    let edited = text.replace(
        "op\tAddClassMethod\tmake\tany",
        "op\tAddClassMethod\tmake\t3",
    );
    assert_ne!(edited, text);
    let report = difference(&edited, &text).expect("a changed row is reported");
    assert!(
        report.contains("- 12: op\tAddClassMethod\tmake\t3"),
        "{report}"
    );
    assert!(
        report.contains("+ 12: op\tAddClassMethod\tmake\tany"),
        "{report}"
    );
}

#[test]
fn classes_check_reports_a_changed_revision_and_an_order_swap() {
    let text = synthetic_table().to_tsv("0123abc");
    let other_revision = synthetic_table().to_tsv("4567def");
    assert!(difference(&text, &other_revision).is_some());
    let swapped = text.replace(
        "creation\tClass\ncreation\tObject\n",
        "creation\tObject\ncreation\tClass\n",
    );
    assert_ne!(swapped, text);
    let report = difference(&swapped, &text).expect("an order swap is reported");
    assert!(
        report.contains("- 6: creation\tObject") && report.contains("+ 7: creation\tObject"),
        "{report}"
    );
}

