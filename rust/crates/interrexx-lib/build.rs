//! Builds the Rexx-written part of the interpreter's own library: this crate's
//! `rexx/` sources, concatenated in `FILES` order into one program.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The library's sources under `rexx/`, in program order. The first holds
/// the main code that runs once the directives of all of them are installed;
/// every other holds only directives.
const FILES: &[&str] = &[
    "bootstrap.rex",
    "collection.rex",
    "ordering.rex",
    "supplier.rex",
    "datetime.rex",
    "file.rex",
    "streamsupplier.rex",
    "command.rex",
    "sets.rex",
    "timespan.rex",
    "misc.rex",
    "traceobject.rex",
    "timer.rex",
    "monitor.rex",
    "stream.rex",
    "queue.rex",
    "orderedcollection.rex",
    "localserver.rex",
];

fn main() {
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    println!("cargo::rerun-if-changed=rexx");
    let mut program: Vec<u8> = Vec::new();
    let mut table = String::from("pub static FILES: &[FileRange] = &[\n");
    for file in FILES {
        let path = Path::new("rexx").join(file);
        let text =
            std::fs::read(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
        let start = program.len();
        program.extend_from_slice(&text);
        // Each file starts on a line of its own, so its lines are counted
        // from its own first line.
        if !program.ends_with(b"\n") {
            program.push(b'\n');
        }
        writeln!(
            table,
            "    FileRange {{ file: {file:?}, start: {start}, end: {} }},",
            program.len()
        )
        .expect("writing to a String cannot fail");
    }
    table.push_str("];\n");
    let built = out.join("library.rex");
    std::fs::write(&built, &program)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", built.display()));
    let generated = format!(
        "// Generated by build.rs from this crate's rexx/ sources. Do not edit.\n\
         pub static LIBRARY: Program = Program {{ name: {:?}, source: include_bytes!({:?}) }};\n\
         {table}",
        NAME, built,
    );
    std::fs::write(out.join("library.rs"), generated).expect("writing library.rs");
}

/// The name the library program runs under.
const NAME: &str = "REXX";
